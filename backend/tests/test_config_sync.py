@respx.mock
async def test_apply_creates_on_the_target_and_strips_the_source_id(stack):
    ids = _ids(stack)
    respx.get(f"{SONARR_URL}/api/v3/customformat").mock(
        return_value=httpx.Response(200, json=[SONARR_CF])
    )
    respx.get(f"{RADARR_URL}/api/v3/customformat").mock(
        return_value=httpx.Response(200, json=[])
    )
    post = respx.post(f"{RADARR_URL}/api/v3/customformat").mock(
        return_value=httpx.Response(201, json=RADARR_CF_AFTER_COPY)
    )

    results = await config_sync.apply(
        stack,
        resource="custom_format",
        source_service_id=ids["Sonarr"],
        item_id=1,
        target_service_ids=[ids["Radarr"]],
    )
    assert results[0].ok is True
    assert results[0].action is Action.CREATE

    import json as _json

    sent = _json.loads(post.calls[0].request.content)
    # Sending the source's id would collide with an unrelated record on the target.
    assert "id" not in sent
    assert sent["name"] == "novoiceover"


