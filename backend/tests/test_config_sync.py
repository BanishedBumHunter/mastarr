# ------------------------------------------------------------- settings store


def test_settings_round_trip_and_coerce(admin_client):
    with Session(get_engine()) as session:
        settings_store.write(session, "session_hours", "24")  # string from a form
        settings_store.write(session, "discovery_hosts", "10.0.0.1, nas.local")
        session.commit()
        stored = settings_store.read_all(session)

    assert stored["session_hours"] == 24
    assert stored["discovery_hosts"] == ["10.0.0.1", "nas.local"]


def test_settings_reject_out_of_range_values(admin_client):
    with Session(get_engine()) as session:
        with pytest.raises(ValueError, match="at least"):
            settings_store.write(session, "session_hours", 0)


def test_settings_reject_unknown_keys(admin_client):
    with Session(get_engine()) as session:
        with pytest.raises(ValueError, match="not an editable setting"):
            settings_store.write(session, "secret_key", "hunter2")


def test_secrets_are_not_editable():
    """The settings surface must have nothing sensitive on it."""
    for forbidden in ("secret_key", "jwt_secret", "data_dir"):
        assert forbidden not in settings_store.EDITABLE


def test_env_beats_the_database_and_reports_why(admin_client, monkeypatch):
    monkeypatch.setenv("MASTARR_SESSION_HOURS", "3")
    from mastarr.config import get_settings, set_db_overrides

    with Session(get_engine()) as session:
        settings_store.write(session, "session_hours", 99)
        session.commit()
        set_db_overrides(settings_store.read_all(session))
        get_settings.cache_clear()

        assert get_settings().session_hours == 3, "database wrongly overrode the env"
        assert settings_store.source_of("session_hours") == "env"
        described = {d["key"]: d for d in settings_store.describe(session)}
        assert described["session_hours"]["locked"] is True


def test_api_refuses_to_edit_an_env_controlled_setting(admin_client, monkeypatch):
    """Accepting the write and then ignoring it would be maddening to debug."""
    monkeypatch.setenv("MASTARR_LOG_LEVEL", "DEBUG")
    response = admin_client.put(
        "/api/settings", json={"key": "log_level", "value": "ERROR"}
    )
    assert response.status_code == 409
    assert "precedence" in response.json()["detail"]


def test_settings_endpoint_lists_provenance(admin_client):
    rows = {r["key"]: r for r in admin_client.get("/api/settings").json()}
    assert set(rows) == set(settings_store.EDITABLE)
    assert rows["session_hours"]["source"] in ("default", "database", "env", "file")
    assert "value" in rows["session_hours"]
