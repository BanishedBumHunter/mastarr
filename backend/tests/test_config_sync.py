@respx.mock
async def test_preview_marks_create_update_identical_and_incompatible(stack):
    ids = _ids(stack)
    respx.get(f"{SONARR_URL}/api/v3/customformat").mock(
        return_value=httpx.Response(200, json=[SONARR_CF])
    )
    # Radarr already has it, byte-identical apart from cosmetics.
    respx.get(f"{RADARR_URL}/api/v3/customformat").mock(
        return_value=httpx.Response(200, json=[RADARR_CF_AFTER_COPY])
    )

    preview = await config_sync.preview(
        stack, resource="custom_format", source_service_id=ids["Sonarr"], item_id=1
    )
    by_name = {t.service_name: t for t in preview.targets}

    assert by_name["Sonarr"].action is Action.INCOMPATIBLE  # it's the source
    assert by_name["Radarr"].action is Action.IDENTICAL
    assert by_name["Prowlarr"].action is Action.INCOMPATIBLE


