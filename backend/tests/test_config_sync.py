@respx.mock
async def test_preview_writes_nothing(stack):
    """The whole point of a preview. A stray write here would be silent."""
    ids = _ids(stack)
    respx.get(f"{SONARR_URL}/api/v3/customformat").mock(
        return_value=httpx.Response(200, json=[SONARR_CF])
    )
